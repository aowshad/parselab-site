/**
 * Generates the dotted world field from real land geometry (Natural Earth,
 * via world-atlas). Samples an equirectangular grid, tests each point against
 * the land polygons, and emits one hex bitmask per row.
 *
 * Output: content/world.ts (~2 KB) — not thousands of committed SVG nodes.
 * Re-run with: node scripts/build-world-dots.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);

const LNG0 = -180, LNG1 = 180;
const LAT0 = 84, LAT1 = -58;          // Antarctica cropped, as in the reference
const COLS = 168;
const ROWS = Math.round(COLS * ((LAT0 - LAT1) / (LNG1 - LNG0)));

const rows = [];
let dots = 0;

for (let r = 0; r < ROWS; r++) {
  const lat = LAT0 - ((r + 0.5) / ROWS) * (LAT0 - LAT1);
  let bits = '';
  for (let c = 0; c < COLS; c++) {
    const lng = LNG0 + ((c + 0.5) / COLS) * (LNG1 - LNG0);
    const on = geoContains(land, [lng, lat]);
    if (on) dots++;
    bits += on ? '1' : '0';
  }
  // pack to hex, 4 bits per char
  let hex = '';
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4).padEnd(4, '0'), 2).toString(16);
  rows.push(hex);
}

const out = `/* GENERATED by scripts/build-world-dots.mjs — do not edit by hand.
   Land mask sampled from Natural Earth. One hex character = four grid cells. */

export const WORLD = {
  cols: ${COLS},
  rows: ${ROWS},
  lng0: ${LNG0},
  lng1: ${LNG1},
  lat0: ${LAT0},
  lat1: ${LAT1},
  /** viewBox height for a 1000-wide box, at true equirectangular aspect */
  height: ${+(1000 * ((LAT0 - LAT1) / (LNG1 - LNG0))).toFixed(2)},
  mask: [
${rows.map((r) => `    '${r}',`).join('\n')}
  ],
};

/** Projects a real coordinate into the same 1000-wide viewBox. */
export function project(lat: number, lng: number) {
  return {
    x: ((lng - WORLD.lng0) / (WORLD.lng1 - WORLD.lng0)) * 1000,
    y: ((WORLD.lat0 - lat) / (WORLD.lat0 - WORLD.lat1)) * WORLD.height,
  };
}
`;

writeFileSync('content/world.ts', out);
console.log(`${COLS}×${ROWS} grid · ${dots} land dots · ${(out.length / 1024).toFixed(1)} KB`);
